/**
 * The list of problem codes (docs/problem-codes.md): every problem the model reports, with an example of its message
 * (from the sample document that makes it happen) and the fixes it offers.
 */
import { parse, type Fix } from './index.ts';
import { SAMPLES } from './samples.ts';

/** What a fix does, in words (the Studio shows its own, translated, labels). */
export function describeFix(fix: Fix): string {
  switch (fix.kind) {
    case 'field': {
      const [kind, name] = fix.target.split(':');
      if (kind === 'attribute') return `asks for \`${name}\``;
      if (kind === 'document') return `asks for the document's \`${name}\``;
      return { alt: 'asks for the alt text', caption: 'asks for the caption', label: 'asks for the title', text: 'asks for the text' }[kind as 'alt'] ?? `asks for ${kind}`;
    }
    case 'remove-attribute': return `removes \`${fix.name}\``;
    case 'rename-attribute': return `renames \`${fix.from}\` to \`${fix.to}\``;
    case 'set-attribute': return `sets \`${fix.name}=${fix.value}\``;
    case 'rename-block': return `renames the block to \`:::${fix.to}\``;
    case 'wrap': return `puts it in \`:::${fix.block}\``;
    case 'heading-level': return `makes it a level ${fix.level} heading`;
    case 'list-type': return fix.ordered ? 'makes it a numbered list' : 'makes it a bulleted list';
    case 'set-front-matter': return `sets \`${fix.key}: ${Array.isArray(fix.value) ? `[${fix.value.join(', ')}]` : fix.value}\``;
  }
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
/** A message quotes Markdown such as ![alt](images/a.png): escaped, so GitHub shows it instead of a broken image. */
const message = (text: string) => cell(text)
  .split(/(\[\^[^\]\s]+\])/)   // footnote syntax as code, or the page would read it as a footnote of its own
  .map((part, i) => i % 2 ? `\`${part}\`` : part.replace(/\[/g, '\\['))
  .join('');

export function problemCodesMarkdown(): string {
  const rows = Object.keys(SAMPLES).sort().map((code) => {
    const p = parse(SAMPLES[code]!).problems.find((x) => x.code === code)!;
    const fixes = p.fixes?.length ? p.fixes.map(describeFix).join('; ') : '';
    return `| \`${code}\` | ${message(p.message)} | ${cell(fixes)} |`;
  });
  return [
    '# LibKa problem codes',
    '',
    '<!-- Generated by packages/model/src/build-codes.ts from the model and its sample documents (packages/model/src/samples.ts). Do not edit by hand. -->',
    '',
    'Every problem `libka lint` (and the Studio, and the MCP server) reports has a code, the line it is on, a message and,',
    'where it is safe, fixes. A fix that changes the text (renames, removals, a wrapping block, a heading level) is applied',
    'in one step the author can undo; a fix that needs words only the author knows (alt text, a caption, a title) never',
    'invents them: it takes the author to the field to fill in. `libka lint --json` lists the codes and fixes too.',
    '',
    `${rows.length} codes. The message is an example: names and values in it come from the document.`,
    '',
    // a LibKa document itself (the docs site builds it): the table has its caption
    ':::table{caption="Problem codes, an example message for each, and the fixes LibKa can apply"}',
    '',   // blank lines around the table: GitHub shows it without the directive's lines as rows
    '| Code | Message (example) | Fixes |',
    '| --- | --- | --- |',
    ...rows,
    '',
    ':::',
    '',
  ].join('\n');
}
