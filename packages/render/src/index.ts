/** One line of the contents: a ## or ### heading, a part (:::section), or the Notes and References sections. */
export interface TocEntry { id: string; text: string; level: 2 | 3; part: boolean }

/** What blocks need to know about the rest of the document: contents, note numbers, sources. */
export interface DocInfo {
  toc: TocEntry[];
  /** Where the automatic contents go: before the first block in them, so after the opening text. */
  contentsAt: number;
  /** How AI took part in the document (front matter "ai"): whether blocks show the AI badge depends on it. */
  ai?: AiProvenance;
  /** Footnote id → its number. */
  notes: Map<string, number>;
  /** How often each note has been referred to so far (for unique back-link targets). */
  noteUses: Map<string, number>;
  footnotes: Footnote[];
  refs: Map<string, Reference>;
  /** Source id → its number in the numeric style (order of first citation). */
  citeNumber: Map<string, number>;
  style: 'numeric' | 'author-date';
  /** A :::toc block replaces the automatic contents. */
  placedToc: boolean;
  /** Whether a reference list is shown at all, and whether a :::references block places it. */
  listRefs: boolean;
  placedRefs: boolean;
}

export const NOTES_ID = 'lk-notes';
export const REFERENCES_ID = 'lk-references';
export const REVISIONS_ID = 'lk-revisions';

export function docInfo(doc: LibkaDocument, labels: Labels): DocInfo {
  const footnotes = doc.footnotes ?? [];
  const refsBlock = doc.blocks.find((b): b is Extract<Block, { type: 'references' }> => b.type === 'references');
  const order = citationOrder(doc);
  const listRefs = Boolean(doc.meta.references?.length) && (Boolean(refsBlock) || order.length > 0);
  const entries = doc.blocks.map((b): TocEntry[] => b.type === 'heading' && b.level <= 3 ? [{ id: b.id, text: plainText(b.text), level: b.level as 2 | 3, part: false }]
    : b.type === 'section' ? [{ id: b.id, text: b.title, level: 2, part: true }]
    : b.type === 'release' ? [{ id: b.id, text: b.version, level: 2, part: false }]
    : b.type === 'decision' ? [{ id: b.id, text: b.title, level: 2, part: false }]
    : b.type === 'revisions' ? [{ id: REVISIONS_ID, text: b.title ?? labels.revisions, level: 2, part: false }]
    : b.type === 'references' && listRefs ? [{ id: REFERENCES_ID, text: b.title ?? labels.references, level: 2, part: false }] : []);
  const toc = entries.flat();
  const first = entries.findIndex((e) => e.length);
  if (footnotes.length) toc.push({ id: NOTES_ID, text: labels.notes, level: 2, part: false });
  if (listRefs && !refsBlock) toc.push({ id: REFERENCES_ID, text: labels.references, level: 2, part: false });
  return {
    toc, contentsAt: first < 0 ? doc.blocks.length : first, ...(doc.meta.ai ? { ai: doc.meta.ai } : {}), footnotes, notes: new Map(footnotes.map((f, i) => [f.id, i + 1])), noteUses: new Map(),
    refs: new Map((doc.meta.references ?? []).map((r) => [r.id, r])), citeNumber: new Map(order.map((id, i) => [id, i + 1])),
    style: refsBlock?.style ?? 'numeric', placedToc: doc.blocks.some((b) => b.type === 'toc'), listRefs, placedRefs: Boolean(refsBlock),
  };
}

export function context(lang: string, target: 'manual' | 'deck' = 'manual', doc?: LibkaDocument): RenderContext {
  const l = langOf(lang);
  let n = 0;
  return { lang: l, labels: LABELS[l], target, dateFormat: doc?.meta.dateFormat ?? DEFAULT_DATE_FORMAT, next: (prefix) => `lk-${prefix}-${++n}`, ...(doc ? { doc: docInfo(doc, LABELS[l]) } : {}) };
}
const DEFAULT = () => context('en');

/** A calendar date (2026, 2026-03, 2026-03-15) as a time element written as the document writes dates; other text stays. */
export function dateHtml(value: string, ctx: Pick<RenderContext, 'lang' | 'dateFormat'>): string {
  const v = value.trim();
  return /^\d{4}(-\d{2}(-\d{2})?)?$/.test(v) ? `<time datetime="${escapeHtml(v)}">${escapeHtml(formatDate(v, ctx.lang, ctx.dateFormat))}</time>` : escapeHtml(value);
}

/** The page runtime inlined into a page, with its labels. */
export function runtimeScript(ctx: RenderContext): string {
  const labels: PageLabels = { copy: ctx.labels.copy, copied: ctx.labels.copied, copyCode: ctx.labels.copyCode, tabs: ctx.labels.tabs };
  // the runtime's text is generated (runtimes.ts), so a minified renderer (the Studio) writes the same script and the
  // same hash as the CLI
  return `(${PAGE_RUNTIME})(${JSON.stringify(labels).replace(/</g, '\\u003c')});`;
}

export function inline(nodes: Inline, ctx?: RenderContext): string {
  return nodes.map((n) => inlineNode(n, ctx)).join('');
}

/** A safe fragment id for a source or note id. */
const fragment = (id: string) => id.replace(/[^\w-]/g, '-');

/** "Doe" from "Doe, Jane"; anything written without a comma (an organisation) stays whole. */
const surname = (author: string) => (author.includes(',') ? author.split(',')[0]!.trim() : author.trim());

/** The short form of a source in author-date style: "Doe and Roe, 2020". */
function authorDate(r: Reference, L: Labels): string {
  const a = r.author ?? [];
  const who = a.length === 0 ? r.title : a.length === 1 ? surname(a[0]!) : a.length === 2 ? `${surname(a[0]!)} ${L.and} ${surname(a[1]!)}` : `${surname(a[0]!)} ${L.etAl}`;
  return `${who}, ${r.year ?? L.noDate}`;
}

function citation(c: Citation, ctx: RenderContext): string {
  const d = ctx.doc!;
  const { open, close, sep, items } = citationParts(c, d, ctx.labels);
  const parts = items.map((it) => {
    const link = it.known && d.listRefs ? `<a href="#lk-ref-${escapeHtml(fragment(it.id))}">${escapeHtml(it.label)}</a>` : escapeHtml(it.label);
    return `${link}${it.locator ? `, ${escapeHtml(it.locator)}` : ''}`;
  });
  return `<span class="lk-cite">${open}${parts.join(sep)}${close}</span>`;
}

function footnoteRef(id: string, label: string, ctx: RenderContext | undefined): string {
  const n = ctx?.doc?.notes.get(id);
  if (!ctx?.doc || !n) return escapeHtml(`[^${label}]`);
  const uses = (ctx.doc.noteUses.get(id) ?? 0) + 1;
  ctx.doc.noteUses.set(id, uses);
  return `<sup class="lk-fn-ref"><a href="#lk-fn-${n}" id="lk-fnref-${n}${uses > 1 ? `-${uses}` : ''}"><span class="lk-visually-hidden">${escapeHtml(ctx.labels.note)} </span>${n}</a></sup>`;
}

function inlineNode(n: PhrasingContent, ctx?: RenderContext): string {
  switch (n.type) {
    case 'footnoteReference': return footnoteRef(n.identifier, n.label ?? n.identifier, ctx);
    case 'text': return escapeHtml(n.value);
    case 'strong': return `<strong>${inline(n.children, ctx)}</strong>`;
    case 'emphasis': return `<em>${inline(n.children, ctx)}</em>`;
    case 'delete': return `<del>${inline(n.children, ctx)}</del>`;
    case 'inlineCode': return `<code>${escapeHtml(n.value)}</code>`;
    case 'break': return '<br>';
    case 'link': {
      const href = safeHref(n.url);
      return href === null ? inline(n.children, ctx) : `<a href="${escapeHtml(href)}">${inline(n.children, ctx)}</a>`;
    }
    case 'image': return escapeHtml(n.alt ?? '');
    default: {
      const d = n as unknown as { type: string; name?: string; children?: PhrasingContent[] };
      if (d.type === 'citation') {
        const c = d as unknown as Citation;
        return ctx?.doc ? citation(c, ctx) : escapeHtml(`[${c.items.map((it) => `@${it.id}${it.locator ? `, ${it.locator}` : ''}`).join('; ')}]`);
      }
      if (d.type === 'textDirective' && d.name === 'kbd') return kbd(kbdKeys(plainText(d.children ?? [])));
      if (d.type === 'textDirective' && d.name === 'badge') {
        const variant = (d as { attributes?: Record<string, string> }).attributes?.variant ?? 'neutral';
        const v = ['neutral', 'info', 'success', 'warning', 'error', 'ai'].includes(variant) ? variant : 'neutral';
        return `<span class="lk-badge lk-badge--${v}">${escapeHtml(plainText(d.children ?? []))}</span>`;
      }
      return escapeHtml(plainText([n]));
    }
  }
}

/** Keys as key caps: one key is a kbd, a combination is a kbd of kbds (HTML spec). */
function kbd(keys: string[]): string {
  const caps = keys.map((k) => `<kbd class="lk-kbd">${escapeHtml(k)}</kbd>`);
  return caps.length === 1 ? caps[0]! : `<kbd class="lk-kbd-combo">${caps.join('+')}</kbd>`;
}

/** Blocks inside list items and callouts: a lone paragraph is unwrapped to keep markup flat. */
function blocks(list: Block[], ctx: RenderContext, unwrapSingle = false): string {
  if (unwrapSingle && list.length === 1 && list[0]?.type === 'paragraph') return inline(list[0].text, ctx);
  return list.map((b) => block(b, ctx)).join('\n');
}

function code(b: Extract<Block, { type: 'code' }>, ctx: RenderContext): string {
  const marked = new Set(b.marked ?? []);
  const lines = b.value.split('\n').map((l, i) => marked.has(i + 1)
    ? `<mark class="lk-code-mark"><span class="lk-visually-hidden">${escapeHtml(ctx.labels.marked)}: </span>${escapeHtml(l)}</mark>` : escapeHtml(l));
  // a figure only when a file name captions it; tabindex so long lines can be scrolled from the keyboard
  const tag = b.title ? 'figure' : 'div';
  return [`<${tag} class="lk-block lk-code">`,
    b.title ? `<figcaption class="lk-code-title">${escapeHtml(b.title)}</figcaption>` : '',
    `<pre class="lk-code-pre" tabindex="0"${b.lang ? ` data-lang="${escapeHtml(b.lang)}"` : ''}><code>${lines.join('\n')}</code></pre>`,
    `</${tag}>`].filter(Boolean).join('');
}

function video(b: Extract<Block, { type: 'video' }>, ctx: RenderContext): string {
  const L = ctx.labels;
  const embed = videoEmbed(b.src);
  const src = safeHref(b.src) ?? '';
  const poster = b.poster ? safeHref(b.poster) : null;
  let player: string;
  if (embed) {
    const url = embed.provider === 'YouTube' ? `https://www.youtube-nocookie.com/embed/${embed.id}?autoplay=1` : `https://player.vimeo.com/video/${embed.id}?dnt=1&autoplay=1`;
    player = `<a class="lk-video-play" href="${escapeHtml(src)}" data-embed="${escapeHtml(url)}" data-title="${escapeHtml(b.title)}">` +
      `${poster ? `<img src="${escapeHtml(poster)}" alt="" class="lk-video-poster">` : ''}` +
      `<span class="lk-video-play-label">${escapeHtml(fill(L.play, { title: b.title }))}</span>` +
      `<span class="lk-video-note">${escapeHtml(fill(L.loadsFrom, { provider: embed.provider }))}</span></a>`;
  } else {
    const captions = b.captions ? safeHref(b.captions) : null;
    player = `<video controls preload="metadata"${poster ? ` poster="${escapeHtml(poster)}"` : ''}>` +
      `<source src="${escapeHtml(src)}">` +
      `${captions ? `<track kind="captions" src="${escapeHtml(captions)}" srclang="${ctx.lang}" label="${escapeHtml(b.title)}" default>` : ''}</video>`;
  }
  return [`<figure class="lk-block lk-video">`, player,
    `<p class="lk-video-print">${escapeHtml(fill(L.videoAt, { title: b.title, src: b.src }))}</p>`,
    `<figcaption>${escapeHtml(b.title)}</figcaption>`,
    `<details class="lk-video-transcript"><summary>${escapeHtml(L.transcript)}</summary><div class="lk-video-transcript-body">${blocks(b.transcript, ctx)}</div></details>`,
    '</figure>'].join('\n');
}

