/** Options against features; yes, no and partial are an icon and a word, the recommended column is named. */
export function comparisonBlock(b: Extract<Block, { type: 'comparison' }>, ctx: RenderContext): string {
  const L = ctx.labels;
  const hl = (i: number) => (b.highlight === i ? ' class="is-highlight"' : '');
  const mark = (m: 'yes' | 'no' | 'partial') => `<span class="lk-mark lk-mark--${m}"><svg class="lk-mark-icon" viewBox="0 0 20 20" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${MARK_ICONS[m]}</svg>${escapeHtml(L.mark[m])}</span>`;
  const head = b.head.map((c, i) => i === 0 ? `<th scope="col">${inline(c, ctx)}</th>`
    : `<th scope="col"${hl(i)}>${inline(c, ctx)}${b.highlight === i ? ` <span class="lk-comparison-badge">${escapeHtml(b.badge ?? L.recommended)}</span>` : ''}</th>`);
  const rows = b.rows.map((r) => `    <tr>${r.map((c, i) => i === 0 ? `<th scope="row">${inline(c.text, ctx)}</th>` : `<td${hl(i)}>${c.mark ? `${mark(c.mark)}${c.text.length ? ` <span class="lk-mark-note">${inline(c.text, ctx)}</span>` : ''}` : inline(c.text, ctx)}</td>`).join('')}</tr>`);
  return [`<div class="lk-table-scroll" role="region" tabindex="0" aria-label="${escapeHtml(b.caption)}">`,
    '<table class="lk-block lk-table lk-comparison">', `  <caption>${escapeHtml(b.caption)}</caption>`,
    `  <thead><tr>${head.join('')}</tr></thead>`, `  <tbody>\n${rows.join('\n')}\n  </tbody>`, '</table>', '</div>'].join('\n');
}

