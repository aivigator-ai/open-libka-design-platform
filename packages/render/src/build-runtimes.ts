// Writes packages/render/src/runtimes.ts: the page and deck runtimes as source text, so every renderer (the CLI and
// the Studio, which is minified) writes exactly the same inline script into a page, and a Content Security Policy
// can name it by hash. With --check, fails if it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pageRuntime } from './page-runtime.ts';
import { deckRuntime } from './deck-runtime.ts';

const out = join(dirname(fileURLToPath(import.meta.url)), 'runtimes.ts');
const text = `// Generated by build-runtimes.ts from page-runtime.ts and deck-runtime.ts (node packages/render/src/build-runtimes.ts).
// Do not edit: change the runtimes, then regenerate. A test fails when this file is stale.

/** The page runtime (page-runtime.ts) as source text, called with its labels. */
export const PAGE_RUNTIME = ${JSON.stringify(pageRuntime.toString())};

/** The deck runtime (deck-runtime.ts) as source text, called with its labels. */
export const DECK_RUNTIME = ${JSON.stringify(deckRuntime.toString())};
`;
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (current !== text) { console.error('render: src/runtimes.ts is out of date; run node packages/render/src/build-runtimes.ts'); process.exit(1); }
  console.log('render: src/runtimes.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log('render: wrote src/runtimes.ts');
}
